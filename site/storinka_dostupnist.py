    'будь-яка клавіша; картка соти після пошуку отримує фокус і має назву для читалки;',
    'автоматична перевірка (axe-core, правила WCAG 2.2 рівнів A і AA) — на 41 типі сторінок, на телефоні й комп\'ютері, у '
