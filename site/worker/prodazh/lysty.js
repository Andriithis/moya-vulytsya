// Шаблони листів, які сервер надсилає сам за розкладом (ZAVDANNYA-132). Ціни — лише з таблиці (tsiny.js).
import TS from './tsiny.js';

const NBSP = ' ';
const suma = (n) => String(n).replace(/\B(?=(\d{3})+(?!\d))/g, NBSP);
const data = (t) => { const d = new Date(t * 1000); return `${String(d.getUTCDate()).padStart(2, '0')}.${String(d.getUTCMonth() + 1).padStart(2, '0')}.${d.getUTCFullYear()}`; };

/** MV-155, П7: лист ОСББ за 3 дні до річного списання. */
export function nahaduvanniaOsbb({ adresa, diie_do, adresaSaitu }) {
  return {
    tema: `Через 3 дні — річна оплата «${TS.nazvy.osbb}»`,
    tekst: `Добрий день!\n\n` +
      `${data(diie_do)} закінчується оплачений рік «${TS.nazvy.osbb}»${adresa ? ` (${adresa})` : ''}. ` +
      `Того ж дня платіжний сервіс автоматично спише ${suma(TS.tsiny.osbb)} грн за наступний рік — з тієї самої картки.\n\n` +
      `Якщо продовжувати не треба — скасуйте підписку в кабінеті до цієї дати: ${adresaSaitu}/kabinet/ ` +
      `(кнопка «Скасувати підписку»). Після скасування нових списань не буде, а оплачений рік діє до кінця.\n\n` +
      `Якщо все гаразд — нічого робити не треба.\n\nМоя вулиця`,
  };
}

/**
 * ZAVDANNYA-161, п. 3 (MV-173): лист «Оплату отримано» — одразу, щойно платіжний сервіс підтвердив оплату (підтвердження
 * угоди в електронній формі, закон «Про електронну комерцію»). Що куплено, ціна, номер і дата, коли й де отримати, як
 * скасувати й повернути — за офертою (розд. 4, 5). Чек дає платіжний сервіс окремо. Без опису подій і без чужих даних.
 * prodovzhennia — чергове списання підписки (той самий лист коротше).
 */
export function oplatuOtrymano({ zam, chas, diie_do = null, adresaSaitu, prodovzhennia = false, kontakt = '' }) {
  const nazva = TS.nazvy[zam.tovar] || zam.tovar;
  const shcho = `${nazva}${zam.adresa ? ` — ${zam.adresa}` : ''}`;
  const pidpyska = !!TS.period_misiatsiv[zam.tovar];
  const rik = TS.period_misiatsiv[zam.tovar] >= 12;
  let koly;
  if (prodovzhennia) {
    koly = `Доступ продовжено до ${data(diie_do)}.`;
  } else if (zam.tovar === 'try') {
    koly = `Першу довідку — ${zam.adresa} — складаємо зараз: посилання прийде окремим листом, зазвичай за кілька хвилин, не пізніше ніж за 1 робочий день. ` +
      `Ще ${TS.dovidok.try - 1} довідки беріть у кабінеті на будь-які будинки, коли потрібно, без строку: ${adresaSaitu}/kabinet/`;
  } else if (zam.tovar === 'osbb') {
    koly = `Доступ відкрито до ${data(diie_do)}. Щомісячна довідка про будинок приходить сама на цю пошту; перша — протягом доби. Усе — у кабінеті: ${adresaSaitu}/kabinet/`;
  } else if (zam.tovar === 'spyurist') {
    koly = `Доступ відкрито до ${data(diie_do)}: таблиці практики — ${adresaSaitu}/pidpysnyk/praktyka/ (увійдіть у кабінет цією поштою).`;
  } else if (pidpyska) {
    koly = `Доступ відкрито до ${data(diie_do)}: карта підписника — ${adresaSaitu}/pidpysnyk/, довідки й «Стежу» — у кабінеті ${adresaSaitu}/kabinet/ (увійдіть цією поштою).` +
      (zam.adresa ? ` Довідка на ${zam.adresa} прийде окремим листом.` : '');
  } else {
    koly = `Посилання на ${zam.tovar === 'zvit' ? 'звіт' : 'довідку'} прийде окремим листом — зазвичай за кілька хвилин, ` +
      `не пізніше ніж за 1 робочий день після оплати. Усі довідки й звіти — також у кабінеті: ${adresaSaitu}/kabinet/`;
  }
  const skasuvaty = pidpyska
    ? `\n\nПідписка продовжується автоматично: ${rik ? 'раз на рік' : 'щомісяця'} платіжний сервіс списує ту саму суму, доки ви не скасуєте. ` +
      `Скасувати — у кабінеті, кнопка «Скасувати підписку»: нових списань не буде, доступ лишається до кінця оплаченого строку.`
    : '';
  return {
    tema: prodovzhennia ? `Оплату отримано: ${nazva} продовжено` : `Оплату отримано: ${nazva}`,
    tekst: `Добрий день!\n\nОплату отримано.\n\n` +
      `Що: ${shcho}\nСума: ${suma(zam.suma)} грн\nЗамовлення: ${zam.id}\nДата: ${data(chas)}\n\n` +
      `${koly}${skasuvaty}\n\n` +
      'Повернення — за офертою (розд. 5): якщо довідку не надіслано за 1 робочий день або доступ не відкрився з нашої вини, ' +
      'повернемо всю суму; від уже надісланої довідки чи вже оплаченого місяця відмовитися не можна — ви просили надіслати одразу. ' +
      `Гроші повертаємо на ту саму картку протягом 10 робочих днів після звернення.${kontakt ? ` Написати нам: ${kontakt}.` : ''}\n` +
      `Оферта: ${adresaSaitu}/zahlushka/oferta.html\n\n` +
      'Фіскальний чек приходить окремим листом.\n\nМоя вулиця',
  };
}
