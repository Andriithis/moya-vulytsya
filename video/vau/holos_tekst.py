"""Текст для синтезованого голосу (ZAVDANNYA-127): числа словами, лише символи, які знає модель Piper.

Модель uk_UA-ukrainian_tts-medium читає лише малі українські літери й кілька знаків — велика літера інакше просто
зникає зі звуку («Сто» звучало як «то»). Без numpy — щоб перевірялося в CI.
"""
from __future__ import annotations

import re

ODYN = ['нуль', 'один', 'два', 'три', 'чотири', "п'ять", 'шість', 'сім', 'вісім', "дев'ять", 'десять', 'одинадцять', 'дванадцять',
        'тринадцять', 'чотирнадцять', "п'ятнадцять", 'шістнадцять', 'сімнадцять', 'вісімнадцять', "дев'ятнадцять"]
DES = ['', '', 'двадцять', 'тридцять', 'сорок', "п'ятдесят", 'шістдесят', 'сімдесят', 'вісімдесят', "дев'яносто"]
SOT = ['', 'сто', 'двісті', 'триста', 'чотириста', "п'ятсот", 'шістсот', 'сімсот', 'вісімсот', "дев'ятсот"]


def _do1000(n, zh=False):
    s = [SOT[n // 100]] if n >= 100 else []
    n %= 100
    if n >= 20:
        s.append(DES[n // 10]); n %= 10
        if n == 0:
            return s
    if n or not s:
        w = ODYN[n]
        if zh and n == 1: w = 'одна'
        if zh and n == 2: w = 'дві'
        s.append(w)
    return s


def chyslo_slovamy(n: int) -> str:
    if n == 0:
        return 'нуль'
    t, r = divmod(n, 1000)
    s = []
    if t:
        o, d = t % 10, t % 100
        forma = 'тисяча' if o == 1 and d != 11 else 'тисячі' if 2 <= o <= 4 and not 12 <= d <= 14 else 'тисяч'
        s += _do1000(t, zh=True) + [forma]
    if r:
        s += _do1000(r)
    return ' '.join(s)


def tekst_dlia_holosu(t: str) -> str:
    t = t.replace('*', '').replace('\n', ' ').replace('—', ',').replace('–', ',').replace('«', '').replace('»', '')
    t = t.replace('’', "'").replace('ʼ', "'").replace('`', "'")
    t = re.sub(r'(\d)[   ](?=\d{3}\b)', r'\1', t)
    t = re.sub(r'\d+', lambda m: chyslo_slovamy(int(m.group())), t)
    # абревіатури модель не читає (після нижнього регістру це «слово» без голосних) — вимовою
    for k, v in ABREVIATURY.items():
        t = re.sub(r'(?<!\w)' + k + r'(?!\w)', v, t)
    t = t.replace('%', ' відсотків').replace('№', 'номер').replace('/', ' ')
    # модель знає лише малі українські літери й кілька знаків: велика літера інакше просто зникає зі звуку
    t = t.lower()
    t = ''.join(ch for ch in t if ch in DOZVOLENI)
    return re.sub(r'\s+', ' ', t).strip()


ABREVIATURY = {'ДТП': 'де-те-пе', 'ТЦ': 'те-це', 'ЄДРСР': 'реєстр судових рішень', 'ОСББ': 'о-ес-бе-бе', 'КУпАП': 'кодекс про адмінправопорушення'}

DOZVOLENI = set(" !',-.:;?абвгдежзийклмнопрстуфхцчшщьюяєіїґ́")
