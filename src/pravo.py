def nazva(label):
    """Повна назва статті за коротким підписом із labels.py.

    'ст.173 КУпАП · дрібне хуліганство' -> 'Дрібне хуліганство'
    Якщо назви немає — повертає порожній рядок. Порожньо краще за приблизно.
    """
    if not label: return ''
    return NAZVY.get(label.split(' · ')[0].strip(), '')


def perevirka(codes):
    """Які підписи лишилися без офіційної назви. Для діагностики під час збірки."""
    return sorted({k for k in codes if not nazva(k)})
