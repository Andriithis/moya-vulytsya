"""Механізм як одиниця аналізу (рішення 31.08.2026).

Тема — папка в законі. Механізм — те, що сталося на місці. Модель ризику
рахується по механізму: у теми «дорожній рух» ДТП (5% подій уночі) і керування
у стані сп'яніння (50% уночі) мають різний час, різні адреси й різну причину,
тож спільний прогноз для них учить модель на шумі.

ЧОМУ ОКРЕМИЙ ФАЙЛ, А НЕ ПРАВКА В labels.py.
labels.py збирається автоматично з переліку категорій ЄДРСР і його ще належить
перебудувати за чинними КК і КУпАП (пункт В1 у STAN.md). Правки руками там
загубляться при першій же перебудові. Тому все, що ми вирішили самі, лежить
тут і накладається поверх labels.py.
"""
import labels as L

# ---- 1. ПОДІЛ ГРУПИ «ДТП» ----
# У labels.py ст.124 КУпАП (ДТП з пошкодженням майна) і ст.286 КК (ДТП з
# потерпілими) склеєні в одну групу ДОР_ДТП. Це різні явища: перше — 38 тисяч
# подій про погнуте крило, друге — те, заради чого пишуть листи. У спільній
# групі друге розчиняється у 20 разів більшій масі першого.
SPLIT = {
    '40696': 'ДОР_ДТП_потерпілі',   # ст.286 КК
    '2019':  'ДОР_ДТП_потерпілі',   # ст.286 КК, старий код категорії
}

# ---- 2. НАЗВИ, ЯКІ МИ УТОЧНИЛИ ----
NAMES = {
    'ДОР_ДТП': 'ДТП з пошкодженням майна',
    'ДОР_ДТП_потерпілі': 'ДТП з потерпілими',
}

def simgroup(code):
    """код категорії -> механізм. Код без групи лишається власною групою."""
    g = SPLIT.get(code) or L.SIMGROUP.get(code)
    if g: return g
    lb = L.CODE.get(code)
    return f'{lb[0]}_{code}' if lb else None

def all_groups():
    """усі відомі механізми"""
    return sorted(set(L.SIMGROUP.values()) | set(SPLIT.values()) | set(NAMES))

def simtheme(sim):
    """механізм -> тема, до якої він належить"""
    return (sim or '').split('_', 1)[0]

def simname(sim):
    """механізм -> людська назва"""
    if not sim: return ''
    return NAMES.get(sim) or L.GROUPNAME.get(sim) or sim.split('_', 1)[-1].replace('_', ' ')

# ---- 3. ЛАТИНСЬКІ ЯКОРІ ----
# Кирилиця у фрагменті URL працює, але ламається при копіюванні посилання.
# Раніше словник слагів жив і в step3_map.py, і в step6_base.py, і вони
# встигли розійтися — посилання з карти вели в нікуди. Тепер джерело одне.
THSLUG = {'ГП': 'gp', 'АЛК': 'alk', 'НАР': 'nar', 'НАС': 'nas',
          'МАЙ': 'may', 'ДОР': 'dor', 'СЕР': 'ser', 'ДОМ': 'dom'}

_TRL = {'а': 'a', 'б': 'b', 'в': 'v', 'г': 'h', 'ґ': 'g', 'д': 'd', 'е': 'e',
        'є': 'ie', 'ж': 'zh', 'з': 'z', 'и': 'y', 'і': 'i', 'ї': 'i', 'й': 'i',
        'к': 'k', 'л': 'l', 'м': 'm', 'н': 'n', 'о': 'o', 'п': 'p', 'р': 'r',
        'с': 's', 'т': 't', 'у': 'u', 'ф': 'f', 'х': 'kh', 'ц': 'ts', 'ч': 'ch',
        'ш': 'sh', 'щ': 'shch', 'ь': '', 'ю': 'iu', 'я': 'ia', "'": '', 'ʼ': ''}

def slug(s):
    out = []
    for ch in (s or '').lower():
        if ch in _TRL: out.append(_TRL[ch])
        elif ch.isalnum(): out.append(ch)
        else: out.append('-')
    r = ''.join(out)
    while '--' in r: r = r.replace('--', '-')
    return r.strip('-')

def anchor(key):
    """якір розділу: тема -> 'gp', механізм -> 'dor-dtp-poterpili'"""
    return THSLUG.get(key) or slug(key)
