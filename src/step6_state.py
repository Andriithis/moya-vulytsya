def problems_block(A, D):
    ER = A['ER']
    out = []
    def card(title, seen, cause, check, tone=''):
        out.append(f'<div class="box {tone}"><h4>{title}</h4>'
                   f'<p><b>Що видно.</b> {seen}</p>'
                   f'<p><b>Можлива причина.</b> {cause}</p>'
                   f'<p><b>Як перевірити на місці.</b> {check}</p></div>')

    # 1) найвагоміший чинник кожної теми -> гіпотеза
    for th in sorted(ER, key=lambda t: -ER[t].get('hit_середовище', 0)):
        d = ER[th]
        for n, w in d.get('фактори', []):
            if w <= 0: continue
            bases = [b for b, _ in parse_factor(n) if b in CAUSE]
            if not bases: continue
            base = bases[0]
            why, chk = CAUSE[base]
            rad = dict(parse_factor(n)).get(base, 0)
            card(f'{esc(d.get("тема", th))}: найвагоміший чинник — '
                 f'{esc(fac_human(n))}',
                 f'На відрізках, де поруч є {esc(base.replace("_", " "))} '
                 f'(радіус {rad} м), подій цієї теми систематично більше; '
                 f'вага чинника {w:+.3f} — найвища серед усіх ознак теми.',
                 why + '.',
                 chk + '.')
            break

    # 2) аномалії
    an = []
    for th, rows in A['anom'].items():
        for r in rows[:3]:
            an.append((r['ev24'], th, r))
    an.sort(key=lambda z: -z[0])
    if an:
        li = ''.join(f"<li><b>{esc(r['name'])}</b> — {esc(L.THEMES.get(th,th))}, "
                     f"{ev} подій, а за середовищем лише {r['rank']}-те місце</li>"
                     for ev, th, r in an[:8])
        card('Місця, які модель не пояснює',
             f'Є відрізки з помітною кількістю подій, які модель ставить у нижню '
             f'половину переліку:<ul>{li}</ul>',
             'Причина є, але її немає в даних: конкретний заклад чи мешканець, '
             'ділянка ремонту, стихійна торгівля, режим роботи, разова подія. '
             'Можливо також, що адресу вписано за замовчуванням.',
             'Це найкорисніші адреси для навчального виїзду: тут відповідь дає '
             'тільки огляд на місці.', 'warn')

    # 3) підозра на «адресу за замовчуванням»
    if A['top_addr']:
        top = A['top_addr'][:5]
        med = sorted(v for _, v in A['top_addr'])[len(A['top_addr']) // 2]
        if top and med and top[0][1] > 8 * med:
            li = ''.join(f'<li>{esc(st)}, {esc(ho)} ({esc(dist)}) — {num(v)} подій</li>'
                         for (dist, st, ho), v in top)
            card('Кілька адрес різко вибиваються з ряду',
                 f'Верхні адреси мають у рази більше подій, ніж решта:<ul>{li}</ul>',
                 'Найімовірніше, це не «найгірші будинки», а адреси установ, які '
                 'вписують у документ, коли точне місце події невідоме: відділ '
                 'поліції, лікарня, суд, вокзал.',
                 'Подивіться, що це за будівля. Якщо це установа — ці адреси треба '
                 'виключати з аналізу, інакше вони тягнутимуть на себе увагу.', 'warn')

    # 4) райони на 10 тисяч
    rates = [(10000.0 * v / A['pop'][d], d, v) for d, v in A['by_dist'].items()
             if A['pop'].get(d)]
    if len(rates) > 3:
        rates.sort(reverse=True)
        med = rates[len(rates) // 2][0]
        hi = [r for r in rates if r[0] > 1.6 * med]
        if hi:
            li = ''.join(f'<li>{esc(d)} — {rate:.0f} подій на 10 тис. мешканців '
                         f'(медіана по місту {med:.0f})</li>' for rate, d, v in hi)
            card('Райони, які вибиваються за подіями на мешканця',
                 f'<ul>{li}</ul>',
                 'Найчастіше це не «гірші люди», а денне населення: у центральних '
                 'районах прописаних мало, а буває там усе місто. Знаменник '
                 'занижений, і показник злітає.',
                 'Порівнювати такі райони коректніше не з іншими районами, а самі '
                 'з собою в часі.')

    # 5) нічні теми
    rowsh = []
    for th, hh in A['th_hour'].items():
        s = sum(hh.values())
        if s < 150: continue
        sh = sum(hh.get(h, 0) for h in (22, 23, 0, 1, 2, 3, 4, 5)) / s
        rowsh.append((sh, th, s))
    if rowsh:
        rowsh.sort(reverse=True)
        sh, th, s = rowsh[0]
        if sh > 0.3:
            card(f'«{esc(L.THEMES.get(th,th))}» — переважно нічна тема',
                 f'{100*sh:.0f}% подій цієї теми, де вказано час, припадає на '
                 f'22:00–06:00.',
                 'Уночі працює менше закладів, менше свідків і гірше освітлення, '
                 'а люди концентруються біля небагатьох відкритих точок.',
                 'Порівняйте перелік ризикованих вулиць цієї теми з тим, що там '
                 'відкрито вночі. Часто це три-чотири адреси на весь район.')

    # 6) прогноз без історії
    fr = [(th, r) for th, rows in A['fresh'].items() for r in rows[:2]]
    if fr:
        li = ''.join(f"<li><b>{esc(r['name'])}</b> — {esc(L.THEMES.get(th,th))}, "
                     f"оцінка {r['score']:.2f}, подій у навчальному році не було</li>"
                     for th, r in fr[:8])
        card('Вулиці, де умови є, а подій ще не фіксували',
             f'<ul>{li}</ul>',
             'Або там справді ще нічого не сталося, або події є, але не потрапляють '
             'у дані — не викликають поліцію, не доходять до суду.',
             'Це найкращий тест для самої моделі: пройдіть цією вулицею й подивіться, '
             'чи схожа вона на проблемні за відчуттям. Якщо схожа — модель права, '
             'і місце варто тримати в полі зору.', 'ok')

    return '\n'.join(out) or '<p class="muted">Замало даних для автоматичних висновків.</p>'
